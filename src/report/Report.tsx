import { Disclosure } from '@/components/ledger/Disclosure'
import { FlowSheet } from '@/components/ledger/FlowSheet'
import { GroupSheet } from '@/components/ledger/GroupSheet'
import { Header } from '@/components/ledger/Header'
import { InsuranceSheet } from '@/components/ledger/InsuranceSheet'
import { CATEGORIES, FLOW_CATEGORIES, GROUPS, type Snapshot } from '@/engine'
import { useI18n } from '@/i18n'
import { periodName } from '@/lib/format'
import { useMediaQuery } from '@/lib/hooks'
import { ResultContent, sides } from '@/screens/ResultContent'
import { Eye } from 'lucide-react'
import type { ReportPayload } from './payload'

const ignore = () => undefined

/** The read-only lines behind the result, showing only groups that hold something. */
function Details({ draft, previous }: { draft: Snapshot; previous?: Snapshot }) {
  const { t } = useI18n()
  const groups = GROUPS.filter((group) => draft.items.some((item) => CATEGORIES.find((entry) => entry.id === item.category)?.group === group.id))
  const hasFlow = (kind: 'income' | 'expense') => (draft.flows ?? []).some((flow) => FLOW_CATEGORIES.find((entry) => entry.id === flow.category)?.kind === kind)
  return (
    <Disclosure title={t.standalone.details}>
      <div className="grid gap-4">
        {groups.map((group) => (
          <GroupSheet key={group.id} group={group.id} draft={draft} previous={previous} readOnly onDraft={ignore} />
        ))}
        {hasFlow('income') && <FlowSheet kind="income" draft={draft} previous={previous} readOnly onDraft={ignore} />}
        {hasFlow('expense') && <FlowSheet kind="expense" draft={draft} previous={previous} readOnly onDraft={ignore} />}
        {draft.period === 'year' && draft.insurance.length > 0 && (
          <div className="pointer-events-none">
            <InsuranceSheet draft={draft} onDraft={ignore} />
          </div>
        )}
      </div>
    </Disclosure>
  )
}

function PreviewNotice() {
  const { t } = useI18n()
  return (
    <p role="status" className="grid gap-1 rounded-2xl bg-caution/14 px-4 py-3">
      <span className="flex items-center gap-2 text-[15px] font-bold">
        <Eye className="size-4.5" aria-hidden="true" />
        {t.standalone.preview}
      </span>
      <span className="text-[14px] leading-relaxed text-muted-foreground">{t.standalone.previewNote}</span>
    </p>
  )
}

/** A standalone, read-only review page generated by the CLI for agents; nothing here is stored. */
export function Report({ payload }: { payload: ReportPayload }) {
  const wide = useMediaQuery('(min-width: 1024px)')
  const draft = payload.snapshots.at(-1)!
  const history = payload.snapshots.slice(0, -1)
  const previous = history.at(-1)
  const header = <Header draft={draft} title={periodName(draft)} />
  const notice = payload.mode === 'preview' && <PreviewNotice />

  if (wide) {
    return (
      <div className="mx-auto grid w-full max-w-[1180px] grid-cols-[minmax(0,1fr)_400px] gap-10 py-8" style={sides}>
        <main className="grid content-start gap-6">
          {header}
          {notice}
          <Details draft={draft} previous={previous} />
        </main>
        <aside className="grid content-start gap-6 pb-8">
          <ResultContent draft={draft} previous={previous} history={history} />
        </aside>
      </div>
    )
  }

  return (
    <div className="mx-auto w-full max-w-xl pb-10" style={sides}>
      <main className="grid gap-5 pt-[max(20px,calc(env(safe-area-inset-top,0px)+12px))]">
        {header}
        {notice}
        <ResultContent draft={draft} previous={previous} history={history} />
        <Details draft={draft} previous={previous} />
      </main>
    </div>
  )
}
